const STOP_WORDS = new Set([
  'a', 'an', 'and', 'as', 'at', 'avoid', 'be', 'by', 'check', 'correct',
  'do', 'for', 'from', 'in', 'into', 'is', 'match', 'no', 'not', 'of', 'on',
  'or', 'over', 'prefer', 'require', 'that', 'the', 'to', 'unnecessary',
  'use', 'when', 'with',
]);

function walk(directory) {
  return readdirSync(directory).flatMap((entry) => {
    const path = join(directory, entry);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

function normalizeDescription(value) {
  const text = value
    .trim()
    .replace(/^['"]|['"]$/g, '')
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('{', '&#123;')
    .replaceAll('}', '&#125;');
  return /[.!?]$/.test(text) ? text : `${text}.`;
}

function tokens(value) {
  return new Set(
    value
      .toLowerCase()
      .replaceAll(/[^a-z0-9]+/g, ' ')
      .split(/\s+/)
      .filter((word) => word.length > 2 && !STOP_WORDS.has(word)),
  );
}

function overlap(left, right) {
  let count = 0;
  for (const value of left) if (right.has(value)) count += 1;
  return count;
}

function readRulePages() {
  return walk(RULES_DIR)
    .filter((path) => path.endsWith('.md') || path.endsWith('.mdx'))
    .map((path) => {
      const content = readFileSync(path, 'utf8');
      const name = content.match(/^title:\s*([^\s]+)$/m)?.[1];
      const description = content.match(/^description:\s*(.+)$/m)?.[1];
      if (!name || !description) {
        throw new Error(`Missing title or description in ${path}`);
      }
      const category = relative(RULES_DIR, path).split(sep)[0];
      return {
        category,
        content,
        description: normalizeDescription(description),
        name,
        nameTokens: tokens(name),
        path,
        url: `/many_lints/docs/rules/${category}/${basename(path).replace(/\.mdx?$/, '')}/`,
      };
    })
    .sort((left, right) => left.name.localeCompare(right.name));
}

function relationScore(rule, candidate) {
  let score = rule.category === candidate.category ? 60 : 0;
  score += overlap(rule.nameTokens, candidate.nameTokens) * 35;
  for (const group of RELATED_GROUPS) {
    if (group.includes(rule.name) && group.includes(candidate.name)) score += 100;
  }
  return score;
}

function relatedRules(rule, pagesByName, pages) {
  const opposingNames = OPPOSITES[rule.name] ?? [];
  const opposing = opposingNames.map((name) => pagesByName.get(name));
  if (opposing.some((page) => page == null)) {
    throw new Error(`Unknown opposing rule configured for ${rule.name}`);
  }

  const ranked = pages
    .filter((candidate) => candidate.name !== rule.name && !opposingNames.includes(candidate.name))
    .map((candidate) => ({ candidate, score: relationScore(rule, candidate) }))
    .sort((left, right) => right.score - left.score || left.candidate.name.localeCompare(right.candidate.name));

  const result = opposing.map((page) => ({ page, opposing: true }));
  for (const { candidate } of ranked) {
    if (result.length >= 4) break;
    result.push({ page: candidate, opposing: false });
  }
  return result;
}

function relatedSection(rule, pagesByName, pages) {
  const items = relatedRules(rule, pagesByName, pages).map(({ page, opposing }) => {
    const prefix = opposing ? '**Opposing convention.** ' : '';
    return `- [\`${page.name}\`](${page.url}) — ${prefix}${page.description}`;
  });
  return `## Related rules\n\n${items.join('\n')}\n`;
}

function updateRulePages(pages) {
  const pagesByName = new Map(pages.map((page) => [page.name, page]));
  for (const page of pages) {
    const withoutGeneratedSection = page.content
      .replace(/\n## Related rules\n[\s\S]*$/, '')
      .trimEnd();
    const updated = `${withoutGeneratedSection}\n\n${relatedSection(page, pagesByName, pages)}`;
    if (CHECK) {
      if (updated !== page.content) throw new Error(`Stale related rules: ${page.path}`);
    } else {
      writeFileSync(page.path, updated);
    }
  }
}

function readSet(source, declaration) {
  const body = source.match(new RegExp(`const ${declaration} = <String>\\{([\\s\\S]*?)\\n\\};`))?.[1];
  if (!body) throw new Error(`Could not read ${declaration} from presets.dart`);
  return [...body.matchAll(/'([a-z0-9_]+)'/g)].map((match) => match[1]);
}

function ruleLink(page) {
  return `[\`${page.name}\`](${page.url})`;
}

function groupedRuleList(names, pagesByName) {
  const byCategory = new Map();
  for (const name of [...names].sort()) {
    const page = pagesByName.get(name);
    if (!page) throw new Error(`Preset references undocumented rule ${name}`);
    const entries = byCategory.get(page.category) ?? [];
    entries.push(page);
    byCategory.set(page.category, entries);
  }
  return [...byCategory.entries()]
    .sort(([left], [right]) => CATEGORY_LABELS[left].localeCompare(CATEGORY_LABELS[right]))
    .map(([category, categoryPages]) => `- **${CATEGORY_LABELS[category]}:** ${categoryPages.map(ruleLink).join(', ')}`)
    .join('\n');
}

function presetPage(pages) {
  const source = readFileSync(SOURCE_PRESETS, 'utf8');
  const pagesByName = new Map(pages.map((page) => [page.name, page]));
  const core = readSet(source, 'coreRules');
  const recommended = readSet(source, '_recommendedOnlyRules');
  const opinionated = readSet(source, '_opinionatedOnlyRules');
  const pedantic = readSet(source, '_pedanticOnlyRules');
  const included = new Set([...core, ...recommended, ...opinionated, ...pedantic]);
  const outside = pages.map((page) => page.name).filter((name) => !included.has(name));

  return `---
title: Presets
description: Choose how strict Many Lints should be and see the exact rules each preset adds.
sidebar:
  order: 3
---

Presets are cumulative starting points. Each level includes every rule from the
levels before it, then adds a clearly defined kind of scrutiny. Choose the
lowest tier whose philosophy matches the project and override individual rules
when the codebase deliberately makes a different choice.

| Preset | Total rules | Adds | Intended use |
|--------|------------:|-----:|--------------|
| \`none\` | 0 | 0 | Explicit opt-out or a fully hand-picked rule set. |
| \`core\` | ${core.length} | ${core.length} | Near-certain defects with almost no stylistic judgement. |
| \`recommended\` | ${core.length + recommended.length} | ${recommended.length} | The default choice for most production projects. |
| \`opinionated\` | ${core.length + recommended.length + opinionated.length} | ${opinionated.length} | A coherent Many Lints house style. |
| \`pedantic\` | ${included.size} | ${pedantic.length} | Maximum uniformity, explicitness, ordering, and structural limits. |

## \`none\`: choose everything yourself

\`none\` is the default and enables no rules. It is useful while evaluating the
plugin, for repositories that enable every rule individually, and for a shared
configuration that should provide options without selecting a policy tier.

\`\`\`yaml
# many_lints.yaml
preset: none
\`\`\`

## \`core\`: bugs, not taste

Use \`core\` when diagnostics must have an exceptionally high signal-to-noise
ratio. It targets contradictory conditions, invalid type relationships,
unreachable behavior, broken lifecycle management, and other code that is very
likely to fail independently of the team's preferred style.

### Rules added by \`core\` (${core.length})

${groupedRuleList(core, pagesByName)}

## \`recommended\`: safe production defaults

\`recommended\` includes \`core\` and adds likely defects, concrete runtime risks,
and broadly accepted Dart and Flutter practices. It avoids naming schemes,
architecture mandates, dependency-specific preferences, and choices on which
healthy codebases commonly disagree. This is the best starting point for most
applications and packages.

### Rules added by \`recommended\` (${recommended.length})

${groupedRuleList(recommended, pagesByName)}

## \`opinionated\`: one coherent house style

\`opinionated\` includes \`recommended\` and chooses a side where several valid
styles exist. It prefers particular widget shapes, collection expressions,
control-flow forms, shorthand syntax, and type-annotation habits. Adopt it when
consistency is worth occasionally disabling a preference that does not fit the
project.

### Rules added by \`opinionated\` (${opinionated.length})

${groupedRuleList(opinionated, pagesByName)}

## \`pedantic\`: uniformity over brevity

\`pedantic\` includes \`opinionated\` and treats mechanical consistency as a goal
in its own right. It adds strict naming, one-declaration-per-file organization,
file/type matching, constructor-first member order, alphabetical parameter and
field order, complexity budgets, explicit callback parameter names, and a full
ban on postfix \`!\` including \`map[key]!\`.

Use it for codebases that want one predictable shape everywhere and accept
configuration work during adoption. Because a plugin cannot activate Dart SDK
lints, combine it with SDK rules such as \`always_specify_types\`,
\`directives_ordering\`, and \`sort_constructors_first\` for the full strict
style.

### Rules added by \`pedantic\` (${pedantic.length})

${groupedRuleList(pedantic, pagesByName)}

## Rules outside every preset (${outside.length})

Some rules need project-specific vocabulary, assume an optional dependency,
enforce the opposite of a convention selected by \`opinionated\`, or are
deliberately opt-in conventions. They remain available by name so presets never
guess package dependencies, silently do nothing without required options,
overreach into project-specific taste, or enable fixes that undo one another.

${groupedRuleList(outside, pagesByName)}

## Moving between presets

Moving upward only adds rules: \`core ⊂ recommended ⊂ opinionated ⊂ pedantic\`.
An explicit per-rule \`enabled:\` value always wins, so a project can adopt a
tier and document its few intentional exceptions:

\`\`\`yaml
# many_lints.yaml
preset: pedantic
rules:
  avoid_long_functions:
    max_lines: 80
  prefer_spacing:
    enabled: false
  use_gap:
    enabled: true
\`\`\`

See [Configuration](/many_lints/docs/configuration/) for option precedence,
per-rule exclusions, diagnostic severity, and both supported config locations.

${GENERATED_MARKER}
`;
}

function updatePresetPage(pages) {
  const updated = presetPage(pages);
  if (CHECK) {
    if (!existsSync(PRESETS_FILE) || readFileSync(PRESETS_FILE, 'utf8') !== updated) {
      throw new Error(`Stale preset catalog: ${PRESETS_FILE}`);
    }
  } else {
    writeFileSync(PRESETS_FILE, updated);
  }
}

const pages = readRulePages();
updateRulePages(pages);
updatePresetPage(pages);
console.log(`${CHECK ? 'Checked' : 'Updated'} ${pages.length} rule pages and the preset catalog.`);
